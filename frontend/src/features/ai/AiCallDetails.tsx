import { Alert, Collapse, Tag } from "antd";
import type { AiAnalysis, AiConfig } from "../../api/ai";
const tasks: Record<string, string> = {
  contract_extract: "Contract field extraction",
  contract_explain: "Difference and risk explanation",
  recommendation_explain: "Recommendation explanation",
};
const states: Record<string, string> = {
  succeeded: "Request succeeded",
  failed: "Request failed",
  not_configured: "Not configured; no model called",
};
export function AiSetup({ config }: { config: AiConfig | null }) {
  if (!config)
    return <p className="muted">Loading model configuration status…</p>;
  return (
    <>
      <p className="muted">
        Model: {config.model ?? "Not configured"} · Request timeout{" "}
        {config.timeout_seconds} seconds
      </p>
      {!config.configured && (
        <Alert
          type="info"
          showIcon
          title="The model API is not enabled or fully configured"
          description="Follow the local AI setup instructions to configure the backend .env and restart it. Keys do not need to be entered here. The rule-based workflow remains available."
        />
      )}
      {config.provider === "test_stub" && (
        <Alert
          type="warning"
          showIcon
          title="Test double mode"
          description="This page is used for local automated verification. Responses are not generated by a real language model."
        />
      )}
    </>
  );
}
export default function AiCallDetails({ record }: { record: AiAnalysis }) {
  return (
    <Collapse
      items={[
        {
          key: "calls",
          label: "This AI call",
          children: (
            <>
              <p className="muted">
                Analysis {record.analysis_id} · {record.created_at}
              </p>
              {record.calls.length === 0 ? (
                <p>No model request was made.</p>
              ) : (
                record.calls.map((call, i) => (
                  <article className="ai-call" key={i}>
                    <strong>{tasks[call.task] ?? call.task}</strong>{" "}
                    <Tag>{states[call.status] ?? call.status}</Tag>
                    <p>
                      Service source:<span>{call.provider}</span>
                      {call.simulated && " · Test double; no real model called"}
                    </p>
                    <p>
                      Model: {call.model ?? "Not configured"} · Duration:{" "}
                      {call.duration_ms} ms
                    </p>
                    <p>Started at: {call.started_at}</p>
                    {!call.attempted && (
                      <p>No request was sent to an external model.</p>
                    )}
                    {call.error_code && <p>Error code: {call.error_code}</p>}
                    {call.provider_request_id && (
                      <p>Service request ID: {call.provider_request_id}</p>
                    )}
                    {call.provider_response_id && (
                      <p>Service response ID: {call.provider_response_id}</p>
                    )}
                    {call.usage && (
                      <p>
                        Usage returned by the service:
                        {Object.entries(call.usage)
                          .map(([key, value]) => `${key}: ${value}`)
                          .join(" · ")}
                      </p>
                    )}
                  </article>
                ))
              )}
              <p className="muted">
                A successful request means a model response was received.
                Fields, references, and business rules are still validated by
                the backend.
              </p>
            </>
          ),
        },
      ]}
    />
  );
}
